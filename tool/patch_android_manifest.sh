#!/usr/bin/env bash
# Allows the classroom's own HTTP, so a video the teacher is casting plays.
#
# The host serves on http://<teacher-address>:8080 because there is no internet
# and no certificate. Everything else in the app talks over that address with
# Dart's own sockets, which are not subject to the platform's cleartext policy
# — which is exactly why joining, the roster and the download all work while a
# video silently fails. The video player is not Dart: on Android it is ExoPlayer
# and on iOS AVPlayer, and both refuse a cleartext URL unless this is declared.
#
# `android/app/src/main/AndroidManifest.xml` is generated by `flutter create` on
# every CI run, so this runs right after that.
set -euo pipefail

manifest="android/app/src/main/AndroidManifest.xml"

if [ ! -f "$manifest" ]; then
  echo "patch-cleartext: no manifest at $manifest" >&2
  exit 1
fi

if grep -q 'usesCleartextTraffic' "$manifest"; then
  echo "patch-cleartext: already allows cleartext"
  exit 0
fi

# The generated <application> tag has no attributes of its own, so inserting
# after the tag name is enough — and if that ever stops being true the check
# below fails loudly rather than leaving a manifest that cannot play.
sed -i 's|<application|<application android:usesCleartextTraffic="true"|' \
  "$manifest"

if ! grep -q 'usesCleartextTraffic="true"' "$manifest"; then
  echo "patch-cleartext: the manifest was not patched" >&2
  exit 1
fi

echo "patch-cleartext: $manifest now allows cleartext for the classroom"